//! CID handling tests for DAG-CBOR.
//!
//! Tests CID serialization and deserialization with CBOR tag 42.

use atproto_dasl::{Cid, CidCore, from_slice, to_vec};
use multihash::Multihash;
use serde::{Deserialize, Serialize};

/// Helper to create a test CID v1 with sha2-256 hash
fn create_test_cid(data: &[u8; 32]) -> Cid {
    let hash = Multihash::<64>::wrap(0x12, data).unwrap();
    Cid::new(CidCore::new_v1(0x71, hash))
}

#[test]
fn test_cid_roundtrip() {
    let cid = create_test_cid(&[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ]);

    let bytes = to_vec(&cid).unwrap();
    let decoded: Cid = from_slice(&bytes).unwrap();

    assert_eq!(cid, decoded);
}

#[test]
fn test_cid_uses_tag_42() {
    let cid = create_test_cid(&[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ]);

    let bytes = to_vec(&cid).unwrap();

    // First byte should be 0xd8 (tag with 1-byte argument)
    assert_eq!(bytes[0], 0xd8);
    // Second byte should be 42 (CID tag)
    assert_eq!(bytes[1], 42);
}

