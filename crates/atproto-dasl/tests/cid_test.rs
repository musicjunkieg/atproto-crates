#[test]
fn test_cid_identity_multibase_prefix() {
    let cid = create_test_cid(&[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ]);

    let bytes = to_vec(&cid).unwrap();

    // Skip tag header: bytes[0]=0xd8, bytes[1]=42
    // Then comes the byte string
    // bytes[2] should be the byte string header (0x58 for 1-byte length prefix, or direct if < 24)

    // Find the bytes content
    let bytes_start = if bytes[2] == 0x58 {
        4 // 0x58 followed by 1-byte length
    } else if bytes[2] >= 0x40 && bytes[2] < 0x58 {
        3 // Direct length encoding (length in lower 5 bits)
    } else {
        panic!("Unexpected byte string encoding");
    };

    // The first byte of the CID bytes should be 0x00 (identity multibase)
    assert_eq!(
        bytes[bytes_start], 0x00,
        "CID bytes must start with 0x00 identity multibase prefix"
    );
}

#[test]
fn test_cid_string_representation() {
    let cid = create_test_cid(&[
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ]);

    // CID should have a string representation (base32 or base58btc)
    let s = cid.to_string();
    assert!(!s.is_empty());

    // Parsing the string back should give the same CID
    let parsed: Cid = s.parse().unwrap();
    assert_eq!(cid, parsed);
}

#[test]
fn test_at_protocol_record_with_cid() {
    // This mimics an AT Protocol record structure
    #[derive(Serialize, Deserialize, Debug, PartialEq)]
    struct Reply {
        root: StrongRef,
        parent: StrongRef,
    }

    #[derive(Serialize, Deserialize, Debug, PartialEq)]
    struct StrongRef {
        uri: String,
        cid: Cid,
    }

    let cid1 = create_test_cid(&[
        0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88,
        0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
        0x88, 0x99,
    ]);

    let cid2 = create_test_cid(&[
        0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee,
        0xff, 0x00,
    ]);

    let reply = Reply {
        root: StrongRef {
            uri: "at://did:plc:abc123/app.bsky.feed.post/xyz".to_string(),
            cid: cid1,
        },
        parent: StrongRef {
            uri: "at://did:plc:def456/app.bsky.feed.post/uvw".to_string(),
            cid: cid2,
        },
    };

    let bytes = to_vec(&reply).unwrap();
    let decoded: Reply = from_slice(&bytes).unwrap();

    assert_eq!(reply, decoded);
}

